// Turns a project into Nginx configuration files.
//
// Output follows the conventions of the reference configuration (main scripts/nginx):
//   - one upstream group per file under upstreams/<category>/, loaded through upstreams.conf
//   - server configurations in conf.d/, loaded by "include conf.d/*.conf" in nginx.conf
//   - files that are switched off go to a "disabled/" subfolder, which those globs do not load
//   - shared proxy_params.conf / ssl_params.conf / security_headers.conf included by path
//   - per-location access/error logs under <log root>/<category>/<location>.{access,error}.log
//   - "# ── Group ───" comments between location groups, proxy_pass last in each location

import { dir, block, comment, blank, raw, marker, forced, aligned, serialize, sections } from './ast.js';
import { expandNodes, FAMILIES, familyKey } from './analyze.js';
import { entityFilePath, locationLogName, MATCH_PREFIX } from './model.js';
import { joinPath, targetPath, dirname } from './paths.js';
import { hostForUrl, isIPv6, stripBrackets } from './net.js';
import { t } from './util.js';
import { APP_NAME } from './version.js';

const SNIPPET_TITLES = {
  proxyParams: 'Shared proxy parameters',
  sslParams: 'Shared TLS parameters',
  securityHeaders: 'Shared security headers',
};

const words = (s) => t(s).split(/\s+/).filter(Boolean);
const opt = (v) => (t(v) ? [t(v)] : []);

/** Returns { files: [{ kind, path, src, enabled, title, nodes, content, lineMap }], snippets, used }. */
export function generate(project) {
  return new Generator(project).run();
}

class Generator {
  constructor(project) {
    this.p = project;
    this.s = project.settings;
    this.used = { proxyParams: [], sslParams: [], securityHeaders: [], websocket: [] };
    this.legacyH2 = this.s.nginxVersion !== '1.25-or-newer';
  }

  run() {
    const s = this.s;
    this.snippets = {
      proxyParams: this.proxyParamsNodes(),
      sslParams: this.sslParamsNodes(),
      securityHeaders: this.securityHeaderNodes(),
    };
    const files = [];
    const includeDisabled = s.package.includeDisabled;

    this.p.servers.forEach((cfg, i) => {
      if (!cfg.enabled && !includeDisabled) return;
      files.push({
        kind: 'server', path: entityFilePath(cfg, s), src: `servers.${i}`, enabled: cfg.enabled,
        title: t(cfg.name) || `Server configuration ${i + 1}`, nodes: this.serverFile(cfg, i),
      });
    });
    this.p.upstreams.forEach((u, i) => {
      if (!u.enabled && !includeDisabled) return;
      files.push({
        kind: 'upstream', path: entityFilePath(u, s), src: `upstreams.${i}`, enabled: u.enabled,
        title: t(u.name) || `Upstream ${i + 1}`, nodes: this.upstreamFile(u, i),
      });
    });
    const index = this.upstreamIndexFile();
    if (index) files.push(index);
    for (const key of Object.keys(this.snippets)) {
      const users = this.used[key].length;
      if (!users) continue;
      files.push({
        kind: 'snippet', snippet: key, path: t(s[key].path), src: `settings.${key}`, enabled: true,
        title: SNIPPET_TITLES[key],
        nodes: [...this.header([`${SNIPPET_TITLES[key]}, included by ${users} block${users === 1 ? '' : 's'}.`]), ...this.snippets[key]],
      });
    }
    const shared = this.sharedFile();
    if (shared) files.push(shared);

    const indent = Number.isInteger(s.format.indent) ? Math.min(8, Math.max(2, s.format.indent)) : 4;
    for (const f of files) {
      const { text, lineMap } = serialize(f.nodes, { indent, align: s.format.alignValues });
      f.content = text;
      f.lineMap = lineMap;
    }
    return { files, snippets: this.snippets, used: this.used };
  }

  // ---------- Helpers ----------
  inc(rel) {
    return targetPath(t(this.s.nginxRoot) || '/etc/nginx', rel);
  }

  includeSnippet(key, src) {
    this.used[key].push(src);
    return dir('include', [this.inc(t(this.s[key].path))], { src, snippet: key });
  }

  header(lines) {
    if (!this.s.format.headerComments) return [];
    return [
      comment(`Generated by ${APP_NAME} from project "${t(this.p.project.name)}".`),
      ...lines.filter(Boolean).map((l) => comment(l)),
      blank(),
    ];
  }

  rule(label, depth = 1) {
    const width = 79 - depth * 4 - 2; // 79 columns, as in the reference conf.d files
    const head = `── ${label} `;
    return head + '─'.repeat(Math.max(3, width - head.length));
  }

  logFormat(own) {
    return t(own) || t(this.s.logFormat);
  }

  logNodes(lg, src, auto) {
    const out = [];
    if (lg.accessLogOff) out.push(dir('access_log', ['off'], { src: `${src}.accessLogOff` }));
    else if (t(lg.accessLog)) out.push(dir('access_log', [t(lg.accessLog), ...opt(this.logFormat(lg.accessLogFormat))], { src: `${src}.accessLog` }));
    else if (auto) out.push(dir('access_log', [auto.access, ...opt(this.logFormat(lg.accessLogFormat))], { src: `${src}.accessLog` }));
    if (t(lg.errorLog)) out.push(dir('error_log', [t(lg.errorLog), ...opt(lg.errorLogLevel)], { src: `${src}.errorLog` }));
    else if (auto) out.push(dir('error_log', [auto.error, ...opt(lg.errorLogLevel)], { src: `${src}.errorLog` }));
    return out;
  }

  autoLogPaths(cfg, name) {
    const base = joinPath(t(this.s.logRoot) || '/var/log/nginx', t(cfg.category));
    return { access: `${base}/${name}.access.log`, error: `${base}/${name}.error.log` };
  }

  generalNodes(x, src) {
    const out = [];
    if (t(x.clientMaxBodySize)) out.push(dir('client_max_body_size', [t(x.clientMaxBodySize)], { src: `${src}.clientMaxBodySize` }));
    if (t(x.sendTimeout)) out.push(dir('send_timeout', [t(x.sendTimeout)], { src: `${src}.sendTimeout` }));
    return aligned(out);
  }

  accessNodes(acc, src) {
    const out = [];
    acc.rules.forEach((r, k) => {
      if (t(r.source)) out.push(dir(r.action, [t(r.source)], { src: `${src}.rules.${k}` }));
    });
    if (t(acc.basicAuthRealm) || t(acc.basicAuthUserFile)) {
      out.push(dir('auth_basic', [forced(t(acc.basicAuthRealm) || 'Restricted')], { src: `${src}.basicAuthRealm` }));
      if (t(acc.basicAuthUserFile)) out.push(dir('auth_basic_user_file', [t(acc.basicAuthUserFile)], { src: `${src}.basicAuthUserFile` }));
    }
    return aligned(out);
  }

  rateLimitNodes(rl, src) {
    if (!t(rl.zone)) return [];
    const args = [`zone=${t(rl.zone)}`];
    if (rl.burst !== null) args.push(`burst=${rl.burst}`);
    if (rl.nodelay) args.push('nodelay');
    const out = [dir('limit_req', args, { src: `${src}.zone` })];
    if (rl.status !== null) out.push(dir('limit_req_status', [String(rl.status)], { src: `${src}.status` }));
    return aligned(out);
  }

  responseHeaderNodes(list, src) {
    const out = [];
    list.forEach((h, k) => {
      if (!t(h.name)) return;
      out.push(dir('add_header', [t(h.name), forced(h.value ?? ''), ...(h.always ? ['always'] : [])], { src: `${src}.${k}` }));
    });
    return aligned(out, { col: true });
  }

  /** Proxy settings as groups of directives: { headers, version, timeouts, buffers, misc }. */
  proxyNodes(ps, src, { includesParams = false } = {}) {
    const hdr = [];
    if (t(ps.hostHeader)) hdr.push(dir('proxy_set_header', ['Host', t(ps.hostHeader)], { src: `${src}.hostHeader` }));
    if (ps.realIp) hdr.push(dir('proxy_set_header', ['X-Real-IP', '$remote_addr'], { src: `${src}.realIp` }));
    if (ps.forwardedFor) hdr.push(dir('proxy_set_header', ['X-Forwarded-For', '$proxy_add_x_forwarded_for'], { src: `${src}.forwardedFor` }));
    if (ps.forwardedProto) hdr.push(dir('proxy_set_header', ['X-Forwarded-Proto', '$scheme'], { src: `${src}.forwardedProto` }));
    ps.requestHeaders.forEach((h, k) => {
      if (t(h.name)) hdr.push(dir('proxy_set_header', [t(h.name), t(h.value)], { src: `${src}.requestHeaders.${k}` }));
    });

    const ver = [];
    const snippetVersion = includesParams && t(this.s.proxyParams.httpVersion);
    if (ps.httpVersion) ver.push(dir('proxy_http_version', [ps.httpVersion], { src: `${src}.httpVersion` }));
    else if (ps.websocket && !snippetVersion) ver.push(dir('proxy_http_version', ['1.1'], { src: `${src}.websocket` }));
    if (ps.websocket) {
      ver.push(dir('proxy_set_header', ['Upgrade', '$http_upgrade'], { src: `${src}.websocket` }));
      ver.push(dir('proxy_set_header', ['Connection', '$connection_upgrade'], { src: `${src}.websocket` }));
      this.used.websocket.push(src);
    } else if (ps.clearConnectionHeader) {
      ver.push(dir('proxy_set_header', ['Connection', ''], { src: `${src}.clearConnectionHeader` }));
    }

    const tmo = [];
    if (t(ps.connectTimeout)) tmo.push(dir('proxy_connect_timeout', [t(ps.connectTimeout)], { src: `${src}.connectTimeout` }));
    if (t(ps.sendTimeout)) tmo.push(dir('proxy_send_timeout', [t(ps.sendTimeout)], { src: `${src}.sendTimeout` }));
    if (t(ps.readTimeout)) tmo.push(dir('proxy_read_timeout', [t(ps.readTimeout)], { src: `${src}.readTimeout` }));

    const buf = [];
    if (ps.buffering) buf.push(dir('proxy_buffering', [ps.buffering], { src: `${src}.buffering` }));
    if (ps.requestBuffering) buf.push(dir('proxy_request_buffering', [ps.requestBuffering], { src: `${src}.requestBuffering` }));
    if (t(ps.bufferSize)) buf.push(dir('proxy_buffer_size', [t(ps.bufferSize)], { src: `${src}.bufferSize` }));
    if (t(ps.buffers)) buf.push(dir('proxy_buffers', words(ps.buffers), { src: `${src}.buffers` }));
    if (t(ps.busyBuffersSize)) buf.push(dir('proxy_busy_buffers_size', [t(ps.busyBuffersSize)], { src: `${src}.busyBuffersSize` }));

    const misc = [];
    if (ps.redirect) misc.push(dir('proxy_redirect', [ps.redirect], { src: `${src}.redirect` }));
    if (ps.sslServerName) misc.push(dir('proxy_ssl_server_name', ['on'], { src: `${src}.sslServerName` }));
    ps.hideHeaders.forEach((h, k) => {
      if (t(h)) misc.push(dir('proxy_hide_header', [t(h)], { src: `${src}.hideHeaders.${k}` }));
    });

    return {
      headers: aligned(hdr, { col: true }),
      version: aligned(ver),
      timeouts: aligned(tmo),
      buffers: aligned(buf),
      misc: aligned(misc),
    };
  }

  // ---------- Shared include files ----------
  proxyParamsNodes() {
    const pp = this.s.proxyParams;
    const src = 'settings.proxyParams';
    const px = this.proxyNodes(pp, src);
    const custom = t(pp.customDirectives) ? [raw(pp.customDirectives, { src: `${src}.customDirectives` })] : [];
    return sections([px.headers, px.version, px.timeouts, px.buffers, px.misc, custom]);
  }

  sslParamsNodes() {
    const sp = this.s.sslParams;
    const src = 'settings.sslParams';
    const proto = [];
    const protocols = sp.protocols.map(t).filter(Boolean);
    if (protocols.length) proto.push(dir('ssl_protocols', protocols, { src: `${src}.protocols` }));
    if (t(sp.ciphers)) proto.push(dir('ssl_ciphers', [t(sp.ciphers)], { src: `${src}.ciphers` }));
    if (sp.preferServerCiphers) proto.push(dir('ssl_prefer_server_ciphers', [sp.preferServerCiphers], { src: `${src}.preferServerCiphers` }));
    const session = [];
    if (t(sp.sessionCache)) session.push(dir('ssl_session_cache', words(sp.sessionCache), { src: `${src}.sessionCache` }));
    if (t(sp.sessionTimeout)) session.push(dir('ssl_session_timeout', [t(sp.sessionTimeout)], { src: `${src}.sessionTimeout` }));
    if (sp.sessionTickets) session.push(dir('ssl_session_tickets', [sp.sessionTickets], { src: `${src}.sessionTickets` }));
    const stapling = [];
    if (sp.stapling) stapling.push(dir('ssl_stapling', ['on'], { src: `${src}.stapling` }));
    if (sp.staplingVerify) stapling.push(dir('ssl_stapling_verify', ['on'], { src: `${src}.staplingVerify` }));
    const resolver = [];
    if (t(sp.resolver)) resolver.push(dir('resolver', words(sp.resolver), { src: `${src}.resolver` }));
    if (t(sp.resolverTimeout)) resolver.push(dir('resolver_timeout', [t(sp.resolverTimeout)], { src: `${src}.resolverTimeout` }));
    const custom = t(sp.customDirectives) ? [raw(sp.customDirectives, { src: `${src}.customDirectives` })] : [];
    return sections([aligned(proto), aligned(session), aligned(stapling), aligned(resolver), custom]);
  }

  /** Headers produced by the security headers settings: [[name, value, field]]. */
  securityHeaderList() {
    const sh = this.s.securityHeaders;
    const out = [];
    if (sh.frameOptions) out.push(['X-Frame-Options', sh.frameOptions, 'frameOptions']);
    if (sh.contentTypeOptions) out.push(['X-Content-Type-Options', 'nosniff', 'contentTypeOptions']);
    if (sh.xssProtection) out.push(['X-XSS-Protection', '1; mode=block', 'xssProtection']);
    if (t(sh.referrerPolicy)) out.push(['Referrer-Policy', t(sh.referrerPolicy), 'referrerPolicy']);
    if (sh.hsts) {
      const age = sh.hstsMaxAge === null ? 31536000 : sh.hstsMaxAge;
      out.push(['Strict-Transport-Security', `max-age=${age}${sh.hstsIncludeSubDomains ? '; includeSubDomains' : ''}${sh.hstsPreload ? '; preload' : ''}`, 'hsts']);
    }
    if (t(sh.permissionsPolicy)) out.push(['Permissions-Policy', t(sh.permissionsPolicy), 'permissionsPolicy']);
    if (t(sh.contentSecurityPolicy)) out.push(['Content-Security-Policy', t(sh.contentSecurityPolicy), 'contentSecurityPolicy']);
    return out;
  }

  securityHeaderNodes() {
    const sh = this.s.securityHeaders;
    const src = 'settings.securityHeaders';
    const list = this.securityHeaderList();
    const hide = sh.hideUpstreamHeaders ? list.map(([name]) => dir('proxy_hide_header', [name], { src: `${src}.hideUpstreamHeaders` })) : [];
    const add = list.map(([name, value, field]) => dir('add_header', [name, forced(value), 'always'], { src: `${src}.${field}` }));
    const custom = t(sh.customDirectives) ? [raw(sh.customDirectives, { src: `${src}.customDirectives` })] : [];
    return sections([aligned(hide), aligned(add, { col: true }), custom]);
  }

  // ---------- Upstream groups ----------
  upstreamFile(u, i) {
    return [
      ...this.header([`Upstream group ${t(u.name)}${t(u.description) ? ` - ${t(u.description)}` : ''}`]),
      this.upstreamBlock(u, i),
    ];
  }

  serverAddress(sv) {
    const a = t(sv.address);
    if (a.startsWith('unix:')) return a;
    const host = hostForUrl(a);
    return sv.port !== null ? `${host}:${sv.port}` : host;
  }

  upstreamBlock(u, i) {
    const src = `upstreams.${i}`;
    const ch = [];
    if (t(u.zoneSize)) ch.push(dir('zone', [t(u.name), t(u.zoneSize)], { src: `${src}.zoneSize` }));
    switch (u.method) {
      case 'least_conn': ch.push(dir('least_conn', [], { src: `${src}.method` })); break;
      case 'ip_hash': ch.push(dir('ip_hash', [], { src: `${src}.method` })); break;
      case 'hash': ch.push(dir('hash', [t(u.hashKey), ...(u.hashConsistent ? ['consistent'] : [])], { src: `${src}.hashKey` })); break;
      case 'random': ch.push(dir('random', u.randomTwo ? ['two', 'least_conn'] : [], { src: `${src}.method` })); break;
      default: break;
    }
    u.servers.forEach((sv, k) => {
      const args = [this.serverAddress(sv)];
      if (sv.weight !== null) args.push(`weight=${sv.weight}`);
      if (sv.maxConns !== null) args.push(`max_conns=${sv.maxConns}`);
      if (sv.maxFails !== null) args.push(`max_fails=${sv.maxFails}`);
      if (t(sv.failTimeout)) args.push(`fail_timeout=${t(sv.failTimeout)}`);
      if (sv.backup) args.push('backup');
      if (sv.down) args.push('down');
      ch.push(dir('server', args, { src: `${src}.servers.${k}`, commented: !sv.enabled, trail: t(sv.comment) || undefined }));
    });
    const ka = [];
    if (u.keepalive !== null) ka.push(dir('keepalive', [String(u.keepalive)], { src: `${src}.keepalive` }));
    if (u.keepaliveRequests !== null) ka.push(dir('keepalive_requests', [String(u.keepaliveRequests)], { src: `${src}.keepaliveRequests` }));
    if (t(u.keepaliveTime)) ka.push(dir('keepalive_time', [t(u.keepaliveTime)], { src: `${src}.keepaliveTime` }));
    if (t(u.keepaliveTimeout)) ka.push(dir('keepalive_timeout', [t(u.keepaliveTimeout)], { src: `${src}.keepaliveTimeout` }));
    ch.push(...aligned(ka));
    if (t(u.customDirectives)) ch.push(raw(u.customDirectives, { src: `${src}.customDirectives` }));
    return block('upstream', [t(u.name)], ch, { src });
  }

  upstreamIndexFile() {
    const s = this.s;
    if (!s.upstreamIndex.enabled) return null;
    const enabled = this.p.upstreams
      .map((u) => ({ u, path: entityFilePath(u, s) }))
      .filter((x) => x.u.enabled && t(x.u.fileName));
    if (!enabled.length) return null;
    const byFile = s.upstreamIndex.style === 'files';
    // A file at the package root is always listed by name: "*.conf" there would also match nginx.conf.
    const targets = [...new Set(enabled.map((x) => {
      const d = dirname(x.path);
      return byFile || !d ? x.path : `${d}/*.conf`;
    }))].sort();
    const nodes = [
      ...this.header([byFile
        ? 'Loads each upstream group file. nginx.conf includes this file in its http block.'
        : 'Loads every upstream group file in these folders. nginx.conf includes this file in its http block.']),
      ...targets.map((tg) => dir('include', [this.inc(tg)], { src: 'settings.upstreamIndex' })),
    ];
    return { kind: 'upstream-index', path: t(s.upstreamIndex.path), src: 'settings.upstreamIndex', enabled: true, title: 'Upstream index', nodes, targets };
  }

  // ---------- Server configurations ----------
  serverFile(cfg, ci) {
    const nodes = [...this.header([`Server configuration "${t(cfg.name)}"${t(cfg.description) ? ` - ${t(cfg.description)}` : ''}`])];
    if (t(cfg.httpDirectives)) nodes.push(raw(cfg.httpDirectives, { src: `servers.${ci}.httpDirectives` }), blank());
    cfg.blocks.forEach((blk, bi) => {
      if (bi > 0) nodes.push(blank());
      nodes.push(...this.serverBlockNodes(cfg, ci, blk, bi));
    });
    return nodes;
  }

  listenAddress(address, port) {
    const a = t(address);
    const p = port !== null && port !== undefined ? String(port) : '';
    if (!a) return p;
    const host = isIPv6(stripBrackets(a)) ? `[${stripBrackets(a)}]` : a;
    return p ? `${host}:${p}` : host;
  }

  listenArgs(l, blk) {
    const first = this.listenAddress(l.address, l.port);
    const args = first ? [first] : [];
    if (l.ssl) args.push('ssl');
    if (l.ssl && blk.http2 && this.legacyH2) args.push('http2');
    if (l.defaultServer) args.push('default_server');
    return args;
  }

  serverBlockNodes(cfg, ci, blk, bi) {
    const src = `servers.${ci}.blocks.${bi}`;
    const sslListens = blk.listen.filter((l) => l.ssl);
    const own = this.serverOwnNodes(cfg, blk, src, sslListens.length > 0);
    const serverEntries = expandNodes(own, this.snippets);
    const locs = this.locationNodes(cfg, ci, blk, bi, serverEntries);
    const children = [...own];
    if (locs.length) {
      if (own.length) children.push(blank());
      children.push(...locs);
    }
    const out = [];
    if (t(blk.label)) out.push(comment(t(blk.label)));
    out.push(block('server', [], children, { src }));
    if (blk.redirectHttp.enabled && sslListens.length) out.push(blank(), ...this.redirectBlock(blk, src, sslListens));
    return out;
  }

  serverOwnNodes(cfg, blk, src, hasSsl) {
    const head = blk.listen.map((l, li) => dir('listen', this.listenArgs(l, blk), { src: `${src}.listen.${li}` }));
    const names = blk.serverNames.map(t).filter(Boolean);
    if (names.length) head.push(dir('server_name', names, { src: `${src}.serverNames` }));
    const h2 = blk.http2 && !this.legacyH2 ? [dir('http2', ['on'], { src: `${src}.http2` })] : [];

    const cert = t(blk.tls.certificate);
    const key = t(blk.tls.certificateKey);
    const tls = [];
    if (cert) tls.push(dir('ssl_certificate', [cert], { src: `${src}.tls.certificate` }));
    if (key) tls.push(dir('ssl_certificate_key', [key], { src: `${src}.tls.certificateKey` }));
    const incl = [];
    if ((hasSsl || cert || key) && blk.tls.includeParams) incl.push(this.includeSnippet('sslParams', `${src}.tls.includeParams`));
    if (blk.securityHeaders) incl.push(this.includeSnippet('securityHeaders', `${src}.securityHeaders`));

    const auto = blk.logging.perLocation ? this.autoLogPaths(cfg, '_default') : null;
    const logs = aligned(this.logNodes(blk.logging, `${src}.logging`, auto));

    const proxyInclude = blk.proxy.includeParams ? [this.includeSnippet('proxyParams', `${src}.proxy.includeParams`)] : [];
    const px = this.proxyNodes(blk.proxy, `${src}.proxy`, { includesParams: blk.proxy.includeParams });
    const errorPages = [];
    blk.errorPages.forEach((e, k) => {
      const codes = e.codes.filter((c) => c !== null).map(String);
      if (codes.length || t(e.target)) errorPages.push(dir('error_page', [...codes, ...opt(e.target)], { src: `${src}.errorPages.${k}` }));
    });
    const custom = t(blk.customDirectives) ? [raw(blk.customDirectives, { src: `${src}.customDirectives` })] : [];

    return sections([
      aligned(head), h2, aligned(tls), incl,
      this.generalNodes(blk, src), logs,
      this.accessNodes(blk.access, `${src}.access`),
      this.rateLimitNodes(blk.rateLimit, `${src}.rateLimit`),
      proxyInclude, px.headers, px.version, px.timeouts, px.buffers, px.misc,
      this.responseHeaderNodes(blk.responseHeaders, `${src}.responseHeaders`),
      errorPages, custom,
    ]);
  }

  redirectBlock(blk, src, sslListens) {
    const r = blk.redirectHttp;
    const port = r.port === null ? 80 : r.port;
    const httpsPort = sslListens[0].port;
    const target = `https://$host${httpsPort && httpsPort !== 443 ? `:${httpsPort}` : ''}$request_uri`;
    const addresses = [...new Set(sslListens.map((l) => t(l.address)))];
    const head = addresses.map((a) => dir('listen', [this.listenAddress(a, port)], { src: `${src}.redirectHttp.port` }));
    const names = blk.serverNames.map(t).filter(Boolean);
    if (names.length) head.push(dir('server_name', names, { src: `${src}.serverNames` }));
    return [
      comment(`Redirect HTTP to HTTPS${t(blk.label) ? ` (${t(blk.label)})` : ''}`),
      block('server', [], [...aligned(head), blank(), dir('return', [String(r.code === null ? 301 : r.code), target], { src: `${src}.redirectHttp.code` })], { src: `${src}.redirectHttp` }),
    ];
  }

  locationNodes(cfg, ci, blk, bi, serverEntries) {
    const out = [];
    const grouped = blk.locations.some((l) => t(l.group));
    let current = null;
    blk.locations.forEach((loc, li) => {
      const g = t(loc.group);
      if (grouped) {
        if (g !== current) {
          if (out.length) out.push(blank());
          if (g) out.push(comment(this.rule(g)));
          current = g;
        }
      } else if (li > 0) {
        out.push(blank());
      }
      if (t(loc.comment)) out.push(comment(t(loc.comment)));
      out.push(this.locationBlock(cfg, ci, blk, bi, loc, li, serverEntries));
    });
    return out;
  }

  locationBlock(cfg, ci, blk, bi, loc, li, serverEntries) {
    const src = `servers.${ci}.blocks.${bi}.locations.${li}`;
    const type = loc.type;
    const proxying = type === 'proxy' || type === 'custom';
    const lg = loc.logging;

    const head = [];
    if (type === 'health' && !lg.accessLogOff && !t(lg.accessLog)) head.push(dir('access_log', ['off'], { src: `${src}.type` }));
    const auto = blk.logging.perLocation && type !== 'health' && type !== 'status' ? this.autoLogPaths(cfg, locationLogName(loc, li)) : null;
    head.push(...this.logNodes(lg, `${src}.logging`, auto));
    const includesParams = proxying && loc.proxy.includeParams;
    if (includesParams) head.push(this.includeSnippet('proxyParams', `${src}.proxy.includeParams`));
    if (loc.internal) head.push(dir('internal', [], { src: `${src}.internal` }));

    const children = [...aligned(head)];
    children.push(...this.accessNodes(loc.access, `${src}.access`));
    const methods = loc.methods.map(t).filter(Boolean);
    if (methods.length) children.push(block('limit_except', methods, [dir('deny', ['all'], { src: `${src}.methods` })], { src: `${src}.methods` }));
    children.push(...this.rateLimitNodes(loc.rateLimit, `${src}.rateLimit`));
    children.push(...this.generalNodes(loc, src));
    children.push(marker('proxy_set_header'));
    if (proxying) {
      const px = this.proxyNodes(loc.proxy, `${src}.proxy`, { includesParams });
      children.push(...px.headers, ...px.version, ...px.timeouts, ...px.buffers, marker('proxy_hide_header'), ...px.misc);
    } else {
      children.push(marker('proxy_hide_header'));
    }
    children.push(marker('add_header'), ...this.responseHeaderNodes(loc.responseHeaders, `${src}.responseHeaders`));
    if (t(loc.customDirectives)) children.push(raw(loc.customDirectives, { src: `${src}.customDirectives` }));
    children.push(...this.targetNodes(loc, src));
    this.applyInheritance(children, serverEntries, src);

    const m = MATCH_PREFIX[loc.match];
    return block('location', [...(m ? [m] : []), t(loc.path)], children, { src, commented: !loc.enabled });
  }

  /**
   * proxy_set_header, add_header and proxy_hide_header are inherited all-or-nothing: a location that
   * sets one of them loses every one from the server block. Repeat the missing ones (by header name) so
   * the location behaves as configured.
   */
  applyInheritance(children, serverEntries, src) {
    const reincluded = new Set();
    for (const fam of FAMILIES) {
      const own = expandNodes(children, this.snippets);
      const idx = children.findIndex((n) => n.t === 'marker' && n.family === fam);
      const ownEntries = own.filter((e) => e.name === fam && !e.isBlock);
      const inherited = serverEntries.filter((e) => e.name === fam && !e.isBlock);
      let repeated = [];
      if (ownEntries.length && inherited.length) {
        const keys = new Set(ownEntries.map((e) => familyKey(e.args)));
        const missing = inherited.filter((e) => !keys.has(familyKey(e.args)));
        if (missing.length) {
          const note = comment(`Repeated from the server block: a location that sets ${fam} does not inherit it`);
          const snippet = this.reincludableSnippet(missing, inherited, keys);
          if (snippet && reincluded.has(snippet)) {
            repeated = [];
          } else if (snippet) {
            reincluded.add(snippet);
            repeated = [note, this.includeSnippet(snippet, `${src}.inherited`)];
          } else {
            repeated = [note, ...missing.map((e) => dir(fam, e.rawArgs, { src: `${src}.inherited`, origin: 'inherited' }))];
          }
        }
      }
      if (idx === -1) continue;
      children.splice(idx, 1, ...repeated);
      // Align the repeated directives together with the location's own ones that follow.
      let end = idx + repeated.length;
      while (end < children.length && children[end].t === 'dir' && children[end].name === fam) end++;
      const run = children.slice(idx, end).filter((n) => n.t === 'dir' && n.name === fam);
      if (run.length > 1) aligned(run, { col: true });
    }
  }

  /**
   * When every missing directive comes from one shared file that holds only header directives, the
   * location can include that file again instead of listing them, as long as it does not set the same
   * headers itself.
   */
  reincludableSnippet(missing, inherited, ownKeys) {
    const origins = new Set(missing.map((e) => e.origin));
    if (origins.size !== 1) return null;
    const origin = [...origins][0];
    if (!origin.startsWith('snippet:')) return null;
    const key = origin.slice('snippet:'.length);
    const entries = expandNodes(this.snippets[key] || [], {}, origin);
    if (!entries.length || entries.some((e) => e.isBlock || !FAMILIES.includes(e.name))) return null;
    if (entries.some((e) => ownKeys.has(familyKey(e.args)) && e.name !== 'proxy_hide_header')) return null;
    if (inherited.some((e) => e.origin === origin) && missing.length !== inherited.filter((e) => e.origin === origin).length) return null;
    return key;
  }

  proxyUrl(pp) {
    const scheme = pp.scheme || 'http';
    const uri = t(pp.uri);
    if (pp.target === 'direct') {
      const addr = t(pp.address);
      if (addr.startsWith('unix:')) return `${scheme}://${addr}:${uri}`;
      return `${scheme}://${hostForUrl(addr)}${pp.port !== null ? `:${pp.port}` : ''}${uri}`;
    }
    return `${scheme}://${t(pp.upstream)}${uri}`;
  }

  targetNodes(loc, src) {
    switch (loc.type) {
      case 'proxy':
        return [dir('proxy_pass', [this.proxyUrl(loc.proxyPass)], { src: `${src}.proxyPass` })];
      case 'return': {
        const args = [];
        if (loc.return.code !== null) args.push(String(loc.return.code));
        if (t(loc.return.value)) args.push(t(loc.return.value));
        return [dir('return', args, { src: `${src}.return` })];
      }
      case 'static': {
        const st = loc.static;
        const out = [];
        if (t(st.root)) out.push(dir('root', [t(st.root)], { src: `${src}.static.root` }));
        if (t(st.alias)) out.push(dir('alias', [t(st.alias)], { src: `${src}.static.alias` }));
        if (t(st.index)) out.push(dir('index', words(st.index), { src: `${src}.static.index` }));
        if (t(st.tryFiles)) out.push(dir('try_files', words(st.tryFiles), { src: `${src}.static.tryFiles` }));
        return aligned(out);
      }
      case 'health':
        return [
          dir('default_type', ['text/plain'], { src: `${src}.health` }),
          dir('return', ['200', `${t(loc.health.text) || 'ok'}\n`], { src: `${src}.health.text` }),
        ];
      case 'status':
        return [dir('stub_status', [], { src: `${src}.type` })];
      default:
        return [];
    }
  }

  sharedFile() {
    const zones = this.p.rateLimitZones;
    const ws = this.used.websocket.length > 0;
    if (!zones.length && !ws) return null;
    const nodes = [...this.header(['Shared http-level definitions used by the server configurations in this package.'])];
    if (ws) {
      nodes.push(
        comment('WebSocket: send "Connection: upgrade" only when the client asks for it; otherwise keep upstream keepalive.'),
        block('map', ['$http_upgrade', '$connection_upgrade'], aligned([dir('default', ['upgrade']), dir('', [''])]), { src: 'settings.sharedHttpPath' }),
      );
      if (zones.length) nodes.push(blank());
    }
    zones.forEach((z, k) => {
      nodes.push(dir('limit_req_zone', [t(z.key), `zone=${t(z.name)}:${t(z.size)}`, `rate=${t(z.rate)}`], { src: `rateLimitZones.${k}` }));
    });
    return { kind: 'shared', path: t(this.s.sharedHttpPath), src: 'settings.sharedHttpPath', enabled: true, title: 'Shared http definitions', nodes };
  }
}
